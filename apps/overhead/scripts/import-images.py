"""Copy rendered zoom levels into assets/puzzles and write src/game/images.ts.

Usage: python scripts/import-images.py <render-out-dir> <render-log>
The renderer lives in scripts/render.py (Sentinel-2 from the AWS open data bucket).
"""
import json
import os
import shutil
import sys

out, log = sys.argv[1], sys.argv[2]
here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
dates = {}
for line in open(log):
    try:
        d = json.loads(line)
        dates[d["id"]] = d["date"]
    except ValueError:
        pass
lines = ["// Generated by scripts/import-images.py. Do not edit by hand.", "export const IMAGES: Record<string, { levels: number[]; captured: string }> = {"]
for key in sorted(dates):
    src = os.path.join(out, key)
    if not os.path.exists(os.path.join(src, "6.jpg")):
        continue
    dst = os.path.join(here, "assets", "puzzles", key)
    os.makedirs(dst, exist_ok=True)
    reqs = []
    for i in range(1, 7):
        shutil.copy(os.path.join(src, f"{i}.jpg"), os.path.join(dst, f"{i}.jpg"))
        reqs.append(f"require('../../assets/puzzles/{key}/{i}.jpg')")
    d = dates[key]
    lines.append(f"  '{key}': {{ captured: '{d[:4]}-{d[4:6]}-{d[6:]}', levels: [{', '.join(reqs)}] }},")
lines.append("};")
open(os.path.join(here, "src", "game", "images.ts"), "w").write("\n".join(lines) + "\n")
print("wrote", len(lines) - 3, "puzzles")
